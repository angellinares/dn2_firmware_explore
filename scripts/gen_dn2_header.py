"""Write csrc/include/dn2_<os>.h from dn2_111.h through the committed address map (issue #382).

    python scripts/gen_dn2_header.py --os 1.12 [--check]
    python scripts/gen_dn2_header.py --os 1.12 --inc csrc/usbprobe/dn2_111.inc [--check]
    python scripts/gen_dn2_header.py --os 1.12 --inc csrc/lfo4/stock_111.h [--check]

--inc translates another file the same way: an assembly include (`|` comments) or a C header
(`/* */` comments). The file it writes sits beside it, its name's `_111` replaced by the OS
(stock_111.h -> stock_112.h; an include without `_111` in its name gives dn2_<os>.inc).

dn2_111.h names the firmware addresses the C code calls or reads. The header for another OS is the
same file with every address literal in its code translated by `dnfw.osport.addr`: the names, the
types and the macros stay, so the C builds for either OS from one source. Comments are copied as they
are, so they keep naming 1.11 addresses; the file's first line says so. TAGS are values that only look
like addresses (chunk magics), copied unchanged. An address the map did not decide stops the run.

--check exits 1 when the file on disk differs from what this writes (for the test suite).
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from dnfw import osport                    # noqa: E402

SOURCE = ROOT / "csrc/include/dn2_111.h"
TAGS = {0x444E4657, 0x434F4445}            # 'DNFW', 'CODE': the platform area's chunk magics
LIT = re.compile(r"0x(4[0-9A-Fa-f]{7})\b")
COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
INC_COMMENT = re.compile(r"\|[^\n]*")


def translate(text: str, os: str, comment: re.Pattern = COMMENT) -> str:
    out, at, missing = [], 0, []
    for m in comment.finditer(text):                     # code between comments is translated
        out.append(_code(text[at:m.start()], os, missing))
        out.append(m.group(0))
        at = m.end()
    out.append(_code(text[at:], os, missing))
    if missing:
        raise SystemExit("not in map_" + os + ".json, read by hand first: " + ", ".join(missing))
    return "".join(out)


def _code(chunk: str, os: str, missing: list[str]) -> str:
    def one(m: re.Match) -> str:
        va = int(m.group(1), 16)
        if va in TAGS:
            return m.group(0)
        try:
            new = osport.addr(os, va)
        except osport.NotPorted:
            missing.append(m.group(0))
            return m.group(0)
        return f"0x{new:08X}" if m.group(1).isupper() or m.group(1).isdigit() else f"0x{new:08x}"
    return LIT.sub(one, chunk)


def render(os: str) -> str:
    text = SOURCE.read_text(encoding="utf-8")
    tag = os.replace(".", "")
    body = translate(text, os)
    body = body.replace("Digitone II OS 1.11:", f"Digitone II OS {os}:", 1)
    body = body.replace("DN2_111_H", f"DN2_{tag}_H")
    head = (f"/* Generated by scripts/gen_dn2_header.py --os {os} from dn2_111.h -- do not edit by hand.\n"
            f" * Every address in the code below is the 1.11 one translated through src/dnfw/osport/map_{os}.json.\n"
            f" * The comments are dn2_111.h's and still name 1.11 addresses. */\n")
    return head + body


def render_inc(source: pathlib.Path, os: str) -> str:
    if source.suffix == ".h":
        tag = os.replace(".", "")
        body = translate(source.read_text(encoding="utf-8"), os).replace("_111_H", f"_{tag}_H")
        return (f"/* Generated by scripts/gen_dn2_header.py --os {os} --inc from {source.name} -- do not edit by hand.\n"
                f" * Every address in the code below is the 1.11 one translated by dnfw.osport.addr.\n"
                f" * The comments are {source.name}'s and still name 1.11 addresses. */\n") + body
    body = translate(source.read_text(encoding="utf-8"), os, INC_COMMENT)
    body = body.replace("MAIN OS 1.11:", f"MAIN OS {os}:", 1)
    return (f"| Generated by scripts/gen_dn2_header.py --os {os} --inc from {source.name} -- do not edit by hand.\n"
            f"| Every address in the code below is the 1.11 one translated through src/dnfw/osport/map_{os}.json.\n"
            f"| The comments are {source.name}'s and still name 1.11 addresses.\n") + body


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--os", required=True)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--inc", type=pathlib.Path, help="an assembly include to translate instead of dn2_111.h")
    a = ap.parse_args()
    if a.inc:
        src = a.inc if a.inc.is_absolute() else ROOT / a.inc
        tag = a.os.replace(".", "")
        out = src.with_name(src.name.replace("_111", f"_{tag}") if "_111" in src.name else f"dn2_{tag}.inc")
        text = render_inc(src, a.os)
    else:
        out = ROOT / f"csrc/include/dn2_{a.os.replace('.', '')}.h"
        text = render(a.os)
    if a.check:
        same = out.exists() and out.read_text(encoding="utf-8") == text
        print(f"{out.name}: {'up to date' if same else 'differs from the generator'}")
        return 0 if same else 1
    out.write_text(text, encoding="utf-8", newline="\n")
    n = len(LIT.findall((INC_COMMENT if a.inc and a.inc.suffix != ".h" else COMMENT).sub("", text)))
    print(f"wrote {out.relative_to(ROOT)}: {n} address literals")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
