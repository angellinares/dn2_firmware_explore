/** The lit runs of a glyph as [x, y, width] triples, one per row segment. */
export function runs(rows) {
  const out = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      let end = x;
      while (row[end + 1] === "#") end++;
      out.push([x, y, end - x + 1]);
      x = end;
    }
  });
  return out;
}

const SVG = "http://www.w3.org/2000/svg";

/** The glyph of mod `id` as an <svg> element, or null when it has none. */
export function glyphSvg(id, doc = document) {
  const rows = GLYPHS[id];
  return rows ? rowsSvg(rows, doc) : null;
}

/** Rows of `#` and `.` as an <svg> element, one <rect> per lit run (an animation frame, too). */
export function rowsSvg(rows, doc = document) {
  const svg = doc.createElementNS(SVG, "svg");
  svg.setAttribute("viewBox", `0 0 ${rows[0].length} ${rows.length}`);
  svg.setAttribute("shape-rendering", "crispEdges");
  svg.setAttribute("fill", "currentColor");
  svg.setAttribute("focusable", "false");
  for (const [x, y, w] of runs(rows)) {
    const r = doc.createElementNS(SVG, "rect");
    r.setAttribute("x", x);
    r.setAttribute("y", y);
    r.setAttribute("width", w);
    r.setAttribute("height", 1);
    svg.append(r);
  }
  return svg;
}
