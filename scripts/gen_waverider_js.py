"""Waverider's data for the browser: `site/js/mods/waverider-code.js`.

    python scripts/gen_waverider_js.py

The Python mod applies two sections (`dnfw.mods.waverider`):

- **MAIN OS (3):** the edits and guards of `waverider_code.json`, then two platform
  `CODE` chunks (the SYN pages, and the +Drive chunk with the /waverider route). The
  browser applies the same JSON, so it is copied as it is.
- **The DSP boot stream (7):** `dnfw.waverider.dsp.section7` refuses any section 7 but
  stock 1.11's (by sha256), so its output is fixed: stock, our blocks spliced in before
  stock's final block, and a few spans written over stock code. This script records
  exactly that: the stock hash, where the final block starts, the inserted blocks, and
  every run of bytes where the result differs from stock-plus-insert. All of it is ours;
  no stock byte is copied.

It refuses to write unless replaying that data on stock gives the Python's section 7
byte for byte. `scripts/js_waverider_check.mjs` then checks the browser against Python.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from dnfw.cli.files import read_image                   # noqa: E402
from dnfw.firmware.load import load                     # noqa: E402
from dnfw.image import bootstream                       # noqa: E402
from dnfw.mods import waverider                         # noqa: E402
from dnfw.waverider import dsp                          # noqa: E402

STOCK = ROOT / "00_Resources/00_Firmware/Digitone_II_OS1.11_dist.zip"
OUT_JS = ROOT / "site/js/mods/waverider-code.js"


def runs(a: bytes, b: bytes) -> list[tuple[int, bytes]]:
    """-> [(offset, b's bytes)] for every run where equal-length a and b differ."""
    out, i = [], 0
    while i < len(a):
        if a[i] == b[i]:
            i += 1
            continue
        j = i
        while j < len(a) and a[j] != b[j]:
            j += 1
        out.append((i, b[i:j]))
        i = j
    return out


def replay(stock: bytes, d: dict) -> bytes:
    out = bytearray(stock[:d["final_offset"]] + bytes.fromhex(d["insert"]) + stock[d["final_offset"]:])
    for p in d["patches"]:
        new = bytes.fromhex(p["bytes"])
        out[p["at"]:p["at"] + len(new)] = new
    return bytes(out)


def main() -> int:
    fw = load(read_image(STOCK))
    stock = fw.container.find(waverider.DSP_STREAM).unpack()
    python = dsp.section7(stock)
    final = bootstream.walk(stock).final.offset
    insert = python[final:final + len(python) - len(stock)]
    base = stock[:final] + insert + stock[final:]
    d = {"stock_sha256": hashlib.sha256(stock).hexdigest(), "stock_length": len(stock),
         "final_offset": final, "insert": insert.hex(), "limit": dsp.STREAM_LIMIT,
         "patches": [{"at": at, "bytes": b.hex()} for at, b in runs(base, python)]}
    if replay(stock, d) != python:
        print("REFUSED: the data does not replay to dnfw.waverider.dsp.section7's output")
        return 1
    spec = waverider.SPEC
    code = {"os": spec["os"], "stock_length": spec["stock_length"], "names": spec["names"],
            "new_type": spec["new_type"], "guards": spec["guards"], "edits": spec["edits"],
            "chunk": {"load": spec["chunk"]["load"], "code": spec["chunk"]["code"]},
            "drive": {"load": spec["drive"]["load"], "code": spec["drive"]["code"]},
            "bus": {"slot_handler": spec["layout"]["wr_slot_id"],
                    "group_displaced": spec["layout"]["wr_group_displaced"]},
            "dsp": d}
    OUT_JS.write_text("// Generated by scripts/gen_waverider_js.py -- do not edit by hand.\n"
                      "export const CODE = " + json.dumps(code, indent=1) + ";\n",
                      encoding="utf-8", newline="\n")
    print(f"wrote {OUT_JS.relative_to(ROOT)}: {len(spec['edits'])} edits, section 7 "
          f"{len(stock):,} -> {len(python):,} B ({len(insert):,} B inserted, "
          f"{len(d['patches'])} patches)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
