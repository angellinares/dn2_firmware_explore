"""Pre-assemble the parameter-slide mod for the browser and the CLI.

    python scripts/gen_pslide_code.py [--os 1.12]

Runs `build_pslide.compose` on the user's own stock image and writes what it changed as data, the
same pattern as `gen_directjump_code.py`:

- `edits`: each site the build changes, whole, with the **stock bytes it expects** (a guard:
  the mod refuses any image that differs) and the new bytes: the eleven hooks and the clear
  mask's operand. The code is not in the image;
- `guards`: the code the hooks rely on (`build_pslide.CONTEXT`), read but not written;
- `code`: the routines, assembled to run at `build_pslide.CODE_VA`, as a platform `CODE` chunk
  (`va`, `blob`, and `bss`, the bytes of state after the code that the loader clears), and
  `labels`, where each routine starts. `labels.slide_frame` is the hook bus's `ev_frame`
  handler.

It refuses to write unless replaying the data on stock gives `compose`'s output byte for byte.

Outputs `src/dnfw/mods/pslide_code.json` and `site/js/mods/pslide-code.js` for 1.11, and with
`--os 1.12` the 1.12 build beside them, `pslide_code_1.12.json` and `pslide-code-1.12.js`.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from dnfw import osport                         # noqa: E402
from dnfw.checkout import resources_dir        # noqa: E402
from dnfw.cli.files import read_image          # noqa: E402
from dnfw.firmware.load import load            # noqa: E402

import build_pslide as ps                      # noqa: E402

def outputs(os: str):
    """(the spec, its web copy) for OS: 1.11 keeps its names (issue #382)"""
    if os == "1.11":
        return ROOT / "src/dnfw/mods/pslide_code.json", ROOT / "site/js/mods/pslide-code.js"
    return ROOT / f"src/dnfw/mods/pslide_code_{os}.json", ROOT / f"site/js/mods/pslide-code-{os}.js"


def main() -> int:
    os = sys.argv[sys.argv.index("--os") + 1] if "--os" in sys.argv else "1.11"
    stock = load(read_image(resources_dir(ROOT) / ps.STOCKS[os])).container.find(ps.MAIN_OS).unpack()
    built = ps.compose(stock, log=lambda *_: None, os=os)
    content = built["content"]

    def at(va, want):
        return osport.site(os, va, want, stock, ps.BASE)

    # one edit per declared site, whole: a byte-run diff would split a site whose new bytes
    # match stock in the middle
    sites = ([(at(va, displaced)[0], len(displaced), what) for va, displaced, _, _, what in ps.HOOKS]
             + [(at(va, old)[0], len(old), what) for va, old, _, what in ps.EDITS])
    edits = [{"va": va, "stock": stock[va - ps.BASE:va - ps.BASE + size].hex(),
              "new": content[va - ps.BASE:va - ps.BASE + size].hex(), "what": what}
             for va, size, what in sorted(sites)]

    replay = bytearray(stock)
    for e in edits:
        new = bytes.fromhex(e["new"])
        replay[e["va"] - ps.BASE:e["va"] - ps.BASE + len(new)] = new
    if bytes(replay) != content:
        raise SystemExit("the edits do not reproduce compose's output; nothing written")

    guards = []
    for va, want, what in ps.CONTEXT:
        va, have = at(va, want)
        guards.append({"va": va, "bytes": have.hex(), "what": what})

    code = {
        "os": f"Digitone II {os}",
        "stock_length": len(stock),
        "edits": edits,
        "guards": guards,
        "labels": built["labels"],
        "code": {"va": ps.CODE_VA, "blob": built["blob"].hex(), "bss": built["bss"]},
    }
    out_json, out_js = outputs(os)
    flag = "" if os == "1.11" else f" --os {os}"
    out_json.write_text(json.dumps(code, indent=1) + "\n", newline="\n")
    out_js.write_text(f"// Generated by scripts/gen_pslide_code.py{flag} -- do not edit by hand.\n"
                      "export const CODE = " + json.dumps(code, indent=1) + ";\n", newline="\n")
    print(f"{len(edits)} edits, a {len(built['blob'])} B CODE chunk at {ps.CODE_VA:#010x} with "
          f"{built['bss']} B of state; ev_frame handler {built['labels']['slide_frame']:#010x}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
