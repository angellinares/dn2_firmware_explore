"""Pre-assemble the arpscale mod (arp offsets in scale) for the CLI and the site.

    python scripts/gen_arpscale_code.py [--os 1.12]

Runs `build_arpscale.compose` on the user's own stock 1.11 image and writes
what it changed as data, the pattern of `gen_lfolength_code.py`:

- `edits`: the hooks, each with the **stock bytes it expects** (a guard:
  the mod refuses any image that differs) and its `jmp` or `jsr`;
- `guards`: the instructions and tables the code relies on
  (`build_arpscale.CONTEXT`), read but not written;
- `code`: the routines, assembled to run at `build_arpscale.CODE_VA`, as a
  platform `CODE` chunk (`va`, `blob`), and `labels`.

It refuses to write unless replaying the data on stock gives `compose`'s output
byte for byte. Nothing is derived from Elektron's tables.

Outputs `src/dnfw/mods/arpscale_code.json` and `site/js/mods/arpscale-code.js`, or with `--os 1.12`
the 1.12 build beside them, `arpscale_code_1.12.json` and `arpscale-code-1.12.js` (issue #382).
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from dnfw import osport
from dnfw.checkout import resources_dir
from dnfw.cli.files import read_image
from dnfw.firmware.load import load

import build_arpscale as bs



def outputs(os: str):
    """(the spec, its web copy) for OS: 1.11 keeps its names (issue #382)"""
    if os == "1.11":
        return ROOT / "src/dnfw/mods/arpscale_code.json", ROOT / "site/js/mods/arpscale-code.js"
    return ROOT / f"src/dnfw/mods/arpscale_code_{os}.json", ROOT / f"site/js/mods/arpscale-code-{os}.js"


def main() -> int:
    os = sys.argv[sys.argv.index("--os") + 1] if "--os" in sys.argv else "1.11"
    stock = load(read_image(resources_dir(ROOT) / bs.STOCKS[os])).container.find(bs.MAIN_OS).unpack()
    built = bs.compose(stock, log=lambda *_: None, os=os)

    def at(va, want):
        return osport.site(os, va, want, stock, bs.BASE)
    content = built["content"]
    blob = built["blob"]

    edits = [{"va": va, "stock": stock_bytes.hex(),
              "new": content[va - bs.BASE:va - bs.BASE + len(stock_bytes)].hex(),
              "what": f"arpscale hook ({label})"}
             for va, stock_bytes, label in [(*at(va, b), lab) for va, b, lab, _ in bs.HOOKS]]
    replay = bytearray(stock)
    for e in edits:
        new = bytes.fromhex(e["new"])
        replay[e["va"] - bs.BASE:e["va"] - bs.BASE + len(new)] = new
    if bytes(replay) != content:
        raise SystemExit("the edits do not reproduce compose's output; nothing written")

    labels = built["labels"]
    code = {
        "os": f"Digitone II {os}",
        "stock_length": len(stock),
        "edits": edits,
        "guards": [{"va": va, "bytes": have.hex()} for va, have in
                   [at(va, want) for va, want, _ in bs.CONTEXT]
                   + [at(va, want) for va, want, _, _ in bs.HOOKS]],
        "labels": labels,
        "code": {"va": bs.CODE_VA, "blob": blob.hex(), "labels": labels},
    }
    if os != "1.11":
        code["flag"] = built["flag"]              # the toggle's byte moves with the settings block
    out_json, out_js = outputs(os)
    flag = "" if os == "1.11" else f" --os {os}"
    out_json.write_text(json.dumps(code, indent=1) + "\n", newline="\n")
    out_js.write_text(f"// Generated by scripts/gen_arpscale_code.py{flag} -- do not edit by hand.\n"
                      "export const CODE = " + json.dumps(code, indent=1) + ";\n", newline="\n")
    print(f"{len(edits)} hooks, a {len(blob)} B CODE chunk at {bs.CODE_VA:#010x}; "
          + ", ".join(f"{k} {v:#010x}" for k, v in labels.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
