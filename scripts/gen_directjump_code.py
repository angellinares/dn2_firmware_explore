"""Pre-assemble the direct-jump mod for the browser and the CLI.

    python scripts/gen_directjump_code.py [--os 1.12]

Runs `build_direct_jump.compose` on the user's own stock 1.11 image and writes what it
changed as data, the same pattern as `gen_reloadconfirm_code.py`:

- `edits`: each site the build changes, whole, with the **stock bytes it expects** (a guard:
  the mod refuses any image that differs) and the new bytes. Only the four hooks and
  the PTN view's vtable entry: the code is not in the image;
- `guards`: the code the hooks rely on (`build_direct_jump.CONTEXT`), read but not written;
- `code`: the routines, assembled to run at `build_direct_jump.CODE_VA`, as a platform `CODE`
  chunk (`va`, `blob`), and `labels`, where each hook's code starts in it (also at the top
  level).

It refuses to write unless replaying the data on stock gives `compose`'s output byte for
byte. Nothing is derived from Elektron's tables.

Outputs `src/dnfw/mods/directjump_code.json` and `site/js/mods/directjump-code.js`, or with
`--os 1.12` the 1.12 build beside them, `directjump_code_1.12.json` and `directjump-code-1.12.js`
(issue #382).
"""

from __future__ import annotations

import json
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from dnfw import osport
from dnfw.checkout import resources_dir
from dnfw.cli.files import read_image
from dnfw.firmware.load import load

import build_direct_jump as dj

def outputs(os: str):
    """(the spec, its web copy) for OS: 1.11 keeps its names (issue #382)"""
    if os == "1.11":
        return ROOT / "src/dnfw/mods/directjump_code.json", ROOT / "site/js/mods/directjump-code.js"
    return ROOT / f"src/dnfw/mods/directjump_code_{os}.json", ROOT / f"site/js/mods/directjump-code-{os}.js"


def main() -> int:
    os = sys.argv[sys.argv.index("--os") + 1] if "--os" in sys.argv else "1.11"
    stock = load(read_image(resources_dir(ROOT) / dj.STOCKS[os])).container.find(dj.MAIN_OS).unpack()
    built = dj.compose(stock, log=lambda *_: None, os=os)
    content = built["content"]
    blob = built["blob"]

    def at(va, want):
        return osport.site(os, va, want, stock, dj.BASE)

    # one edit per declared site, whole: a byte-run diff would split a site whose new bytes
    # happen to match stock in the middle (0x400da6e6: 43f9... -> 4ef9...)
    n = len(stock)
    sites = ([(at(va, displaced)[0], len(displaced)) for va, displaced, _ in dj.HOOKS]
             + [(at(va, struct.pack(">I", pointer))[0], 4) for va, pointer, _ in dj.POINTERS])
    edits = [{"va": va, "stock": stock[va - dj.BASE:va - dj.BASE + size].hex(),
              "new": content[va - dj.BASE:va - dj.BASE + size].hex(), "what": "direct-jump hook"}
             for va, size in sorted(sites)]

    replay = bytearray(stock)
    for e in edits:
        new = bytes.fromhex(e["new"])
        replay[e["va"] - dj.BASE:e["va"] - dj.BASE + len(new)] = new
    if bytes(replay) != content:
        raise SystemExit("the edits do not reproduce compose's output; nothing written")

    labels = built["labels"]
    code = {
        "os": f"Digitone II {os}",
        "stock_length": n,
        "edits": edits,
        "guards": [{"va": va, "bytes": have.hex()} for va, have in [at(va, want) for va, want, _ in dj.CONTEXT]],
        "labels": labels,
        "code": {"va": dj.CODE_VA, "blob": blob.hex(), "labels": labels},
    }
    if os != "1.11":
        code["flag"] = built["flag"]              # the switch's byte moves with the settings block
    out_json, out_js = outputs(os)
    flag = "" if os == "1.11" else f" --os {os}"
    out_json.write_text(json.dumps(code, indent=1) + "\n", newline="\n")
    out_js.write_text(f"// Generated by scripts/gen_directjump_code.py{flag} -- do not edit by hand.\n"
                      "export const CODE = " + json.dumps(code, indent=1) + ";\n", newline="\n")
    print(f"{len(edits)} edits, a {len(blob)} B CODE chunk at {dj.CODE_VA:#010x}; "
          + ", ".join(f"{k} {v:#010x}" for k, v in labels.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
