"""Copy the 3x5 font into the site, which cannot read a JSON file next to Python.

    python scripts/gen_font3x5.py

Writes `site/js/font3x5.js` (an ES module, for the boot screen tools) and
`site/js/glyph-tools/glyph_font3x5.js` (a classic script, for the glyph editor's Text
tool, so that page also works when opened from disk) from `src/dnfw/font3x5.json`.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEAD = "// Generated by scripts/gen_font3x5.py from src/dnfw/font3x5.json -- do not edit by hand.\n"


def module_text(font: dict) -> str:
    return HEAD + f"export const FONT = {json.dumps(font['glyphs'], indent=1)};\n"


def classic_text(font: dict) -> str:
    return (HEAD + "// The glyph editor's Text tool reads it as GlyphFont3x5 (see glyph_text.js).\n"
            f"(typeof globalThis !== \"undefined\" ? globalThis : this).GlyphFont3x5 = {json.dumps(font, indent=1)};\n")


if __name__ == "__main__":
    font = json.loads((ROOT / "src/dnfw/font3x5.json").read_text())
    (ROOT / "site/js/font3x5.js").write_bytes(module_text(font).encode("utf-8"))
    (ROOT / "site/js/glyph-tools/glyph_font3x5.js").write_bytes(classic_text(font).encode("utf-8"))
    print(f"{len(font['glyphs'])} glyphs")
