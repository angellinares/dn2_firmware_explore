  /** The icon as SVG markup, `size` CSS pixels square (a whole multiple of 16 keeps it crisp). */
  function iconSvg(name, size = 32) {
    const rows = ICONS[name];
    if (!rows) return "";
    let rects = "";
    rows.forEach((row, y) => row.replace(/#+/g, (run, x) => {
      rects += `<rect x="${x}" y="${y}" width="${run.length}" height="1"/>`;
      return run;
    }));
    return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" ` +
      `fill="currentColor" aria-hidden="true" focusable="false">${rects}</svg>`;
  }

